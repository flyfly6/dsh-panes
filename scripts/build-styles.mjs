/**
 * Builds src/styles/tailwind.css into a CSS string module that the client bundle
 * imports and injects as `<style data-plugin-css>`.
 *
 * Why a generated module: plugin styles must arrive with the bundle (the module
 * system only serves JS), and tsdown does not turn a .css import into a string.
 */
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = resolve(root, 'lib/tailwind.css')

mkdirSync(dirname(out), { recursive: true })
execFileSync(
  resolve(root, 'node_modules/.bin/tailwindcss'),
  ['-c', resolve(root, 'tailwind.config.cjs'), '-i', resolve(root, 'src/styles/tailwind.css'), '-o', out, '--minify'],
  { stdio: 'inherit', cwd: root },
)

// xterm ships its own stylesheet; a plugin bundle must carry it as text.
const xterm = readFileSync(resolve(root, 'node_modules/@xterm/xterm/css/xterm.css'), 'utf8')
const css = `${readFileSync(out, 'utf8')}\n${xterm}`
const target = resolve(root, 'src/generated/styles.ts')
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, `/* Generated by scripts/build-styles.mjs — do not edit. */\nexport default ${JSON.stringify(css)}\n`)
process.stdout.write(`styles: ${css.length} bytes -> src/generated/styles.ts\n`)
