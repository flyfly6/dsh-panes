/**
 * Builds src/styles/tailwind.css into a CSS string module that the client bundle
 * imports and injects as `<style data-plugin-css>`.
 *
 * Why a generated module: plugin styles must arrive with the bundle (the module
 * system only serves JS), and tsdown does not turn a .css import into a string.
 */
import { execFileSync } from 'node:child_process'
import { createRequire } from 'node:module'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = resolve(root, 'lib/tailwind.css')

mkdirSync(dirname(out), { recursive: true })
execFileSync(
  resolve(root, 'node_modules/.bin/tailwindcss'),
  ['-c', resolve(root, 'tailwind.config.cjs'), '-i', resolve(root, 'src/styles/tailwind.css'), '-o', out, '--minify'],
  { stdio: 'inherit', cwd: root },
)

/**
 * Inline a stylesheet, resolving `@import url(...)` as it goes: the editor kits
 * (BlockNote + Mantine) ship an entry file that is nothing but imports, and the
 * bundle can only carry text — nothing resolves a CSS import at runtime.
 */
const nodeRequire = createRequire(import.meta.url)
function readCss(file, seen = new Set()) {
  const absolute = nodeRequire.resolve(file)
  if (seen.has(absolute)) return ''
  seen.add(absolute)
  const css = readFileSync(absolute, 'utf8')
  return css.replace(/@import\s+url\((['"]?)([^'")]+)\1\)\s*;?/g, (_match, _quote, spec) => {
    const resolved = spec.startsWith('.') ? resolve(dirname(absolute), spec) : spec
    try {
      return readCss(resolved, seen)
    } catch (error) {
      throw new Error(`build-styles: cannot resolve CSS import ${spec} from ${absolute}: ${error.message}`)
    }
  })
}

// xterm and BlockNote ship their own stylesheets; a plugin bundle must carry
// them as text (the module system only serves JS, and tsdown does not turn a
// .css import into a string).
const xterm = readCss('@xterm/xterm/css/xterm.css')
const blocknote = readCss('@blocknote/ariakit/style.css')
const css = `${readFileSync(out, 'utf8')}\n${xterm}\n${blocknote}`
const target = resolve(root, 'src/generated/styles.ts')
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, `/* Generated by scripts/build-styles.mjs — do not edit. */\nexport default ${JSON.stringify(css)}\n`)
process.stdout.write(`styles: ${css.length} bytes -> src/generated/styles.ts\n`)
